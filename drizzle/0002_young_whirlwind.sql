	`branch` text NOT NULL,
	`worktree` text NOT NULL,
	`status` text NOT NULL,
	`summary` text DEFAULT '' NOT NULL,
	`error` text,
	`mr_url` text,
	`session` text,
	`runs` integer DEFAULT 0 NOT NULL,
	`usage` text,
	`created` real NOT NULL,
	`updated` real NOT NULL
);
